# Reference solver: in-memory key-value store, levels 1–4
# ══════════════════════════════════════════════════════════════════


class KVStore:
    """Level N semantics are a superset of level N-1 (regression-safe).
    `timed=True` (levels 3+) expects a leading timestamp on every line."""

    def __init__(self) -> None:
        self.data: dict[str, tuple[str, int | None]] = {}  # key -> (value, expire_at)
        self.backups: list[tuple[int, dict[str, tuple[str, int | None]]]] = []

    def _alive(self, key: str, ts: int) -> bool:
        item = self.data.get(key)
        return item is not None and (item[1] is None or ts < item[1])

    def _live(self, ts: int) -> dict[str, str]:
        return {k: v for k, (v, exp) in self.data.items() if exp is None or ts < exp}

    def run(self, script: str, timed: bool) -> list[str]:
        out: list[str] = []
        lines = script.strip("\n").split("\n")
        for raw in lines[1:]:  # first line is the command count
            parts = raw.split()
            ts = 0
            if timed:
                ts = int(parts[0])
                parts = parts[1:]
            cmd, args = parts[0], parts[1:]
            if cmd == "SET":
                key, value = args[0], args[1]
                ttl = int(args[2]) if len(args) > 2 else None
                self.data[key] = (value, ts + ttl if ttl is not None else None)
            elif cmd == "GET":
                out.append(self.data[args[0]][0] if self._alive(args[0], ts) else "null")
            elif cmd == "DELETE":
                alive = self._alive(args[0], ts)
                self.data.pop(args[0], None)
                out.append("true" if alive else "false")
            elif cmd == "SCAN":
                live = self._live(ts)
                hits = sorted(k for k in live if k.startswith(args[0]))
                out.append(",".join(f"{k}={live[k]}" for k in hits) if hits else "-")
            elif cmd == "COUNT":
                out.append(str(len(self._live(ts))))
            elif cmd == "BACKUP":
                snapshot = {
                    k: (v, None if exp is None else exp - ts)
                    for k, (v, exp) in self.data.items()
                    if exp is None or ts < exp
                }
                self.backups.append((ts, snapshot))
                out.append(str(len(snapshot)))
            elif cmd == "RESTORE":
                target = int(args[0])
                candidates = [b for b in self.backups if b[0] <= target]
                if not candidates:
                    out.append("-")
                else:
                    _, snapshot = max(candidates, key=lambda b: b[0])
                    self.data = {
                        k: (v, None if rem is None else ts + rem)
                        for k, (v, rem) in snapshot.items()
                    }
                    out.append("ok")
            else:
                raise ValueError(f"unknown command {cmd}")
        return out


def _script(*cmds: str) -> str:
    return f"{len(cmds)}\n" + "\n".join(cmds) + "\n"


def _timed(script: str) -> str:
    """Re-express an untimed script with increasing timestamps (level 3+)."""
    lines = script.strip("\n").split("\n")
    return lines[0] + "\n" + "\n".join(f"{i} {line}" for i, line in enumerate(lines[1:], 1)) + "\n"


