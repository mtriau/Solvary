async def _ensure_problem(
    prob_repo: SQLAlchemyProblemRepository,
    tc_repo: SQLAlchemyTestCaseRepository,
    built: tuple[Problem, list[TestCase]],
    admin_id: str,
) -> Problem:
    problem, cases = built
    existing = await prob_repo.get_by_slug(problem.slug)
    if existing:
        print(f"  problem {problem.slug}: exists")
        return existing
    problem.created_by = admin_id
    await prob_repo.create(problem)
    for c in cases:
        await tc_repo.create(c)
    print(f"  problem {problem.slug}: created ({len(cases)} cases)")
    return problem


async def seed() -> None:
    async with async_session_factory() as session:
        admin = (
            await session.execute(select(UserRow).where(UserRow.role == "admin").limit(1))
        ).scalar_one_or_none()
        if admin is None:
            raise SystemExit("No admin user — run `python -m scripts.seed_admin` first")

        prob_repo = SQLAlchemyProblemRepository(session)
        tc_repo = SQLAlchemyTestCaseRepository(session)
        tpl_repo = SQLAlchemyInterviewTemplateRepository(session)
        stage_repo = SQLAlchemyInterviewStageRepository(session)

        # ── kv-store-levels ────────────────────────────────────────
        if await tpl_repo.get_by_slug("kv-store-levels"):
            print("template kv-store-levels: exists")
        else:
            print("template kv-store-levels:")
            problems = [
                await _ensure_problem(prob_repo, tc_repo, built, admin.id)
                for built in kv_level_problems()
            ]
            template = InterviewTemplate(
                id=f"itpl_{uuid.uuid4().hex[:8]}",
                slug="kv-store-levels",
                title="Key-Value Store (4 levels, 90 min)",
                description_md=(
                    "One evolving problem in four levels, the way industry coding"
                    " assessments run it: each level adds requirements on top of the last"
                    " and its tests include the earlier levels. Same code buffer throughout."
                    " Suggested pacing: 15 / 20 / 25 / 30 minutes."
                ),
                format="levels",
                duration_s=90 * 60,
                advance="free",
                pacing="coached",
                created_by=admin.id,
            )
            await tpl_repo.create(template)
            budgets = [15, 20, 25, 30]
            for i, (p, (title, _)) in enumerate(zip(problems, LEVEL_STATEMENTS), 1):
                await stage_repo.create(
                    InterviewStage(
                        id=f"istg_{uuid.uuid4().hex[:8]}",
                        template_id=template.id,
                        ordinal=i,
                        problem_id=p.id,
                        title=title,
                        budget_s=budgets[i - 1] * 60,
                    )
                )
            print("  created")

        # ── warmup-questions ───────────────────────────────────────
        if await tpl_repo.get_by_slug("warmup-questions"):
            print("template warmup-questions: exists")
        else:
            print("template warmup-questions:")
            catalog = {}
            for slug in ("two-sum", "fizzbuzz", "mean-of-list"):
                p = await prob_repo.get_by_slug(slug)
                if p is None:
                    print(
                        f"  missing catalog problem {slug} — run scripts.seed_problems"
                        " first; skipped"
                    )
                    break
                catalog[slug] = p
            else:
                merge = await _ensure_problem(
                    prob_repo, tc_repo, merge_intervals_problem(), admin.id
                )
                template = InterviewTemplate(
                    id=f"itpl_{uuid.uuid4().hex[:8]}",
                    slug="warmup-questions",
                    title="Warm-up (4 questions, 60 min)",
                    description_md=(
                        "Four independent problems of rising difficulty, all visible from"
                        " the start — jump between them freely. Suggested pacing:"
                        " 10 / 10 / 15 / 25 minutes."
                    ),
                    format="questions",
                    duration_s=60 * 60,
                    created_by=admin.id,
                )
                await tpl_repo.create(template)
                plan = [
                    (catalog["fizzbuzz"], "Question 1 — FizzBuzz", 10),
                    (catalog["two-sum"], "Question 2 — Two Sum", 10),
                    (catalog["mean-of-list"], "Question 3 — Mean of a List", 15),
                    (merge, "Question 4 — Merge Intervals", 25),
                ]
                for i, (p, title, minutes) in enumerate(plan, 1):
                    await stage_repo.create(
                        InterviewStage(
                            id=f"istg_{uuid.uuid4().hex[:8]}",
                            template_id=template.id,
                            ordinal=i,
                            problem_id=p.id,
                            title=title,
                            budget_s=minutes * 60,
                        )
                    )
                print("  created")

        await session.commit()


if __name__ == "__main__":
    asyncio.run(seed())
