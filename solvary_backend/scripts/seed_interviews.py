def merge_intervals(stdin: str) -> list[str]:
    lines = stdin.strip().split("\n")
    n = int(lines[0])
    iv = sorted(tuple(map(int, lines[i + 1].split())) for i in range(n))
    merged: list[list[int]] = []
    for a, b in iv:
        if merged and a <= merged[-1][1]:
            merged[-1][1] = max(merged[-1][1], b)
        else:
            merged.append([a, b])
    return [f"{a} {b}" for a, b in merged]


MERGE_INPUTS = [
    ("4\n1 3\n2 6\n8 10\n15 18\n", True),
    ("2\n1 4\n4 5\n", True),
    ("1\n5 5\n", False),
    ("5\n5 7\n1 2\n3 4\n2 3\n8 9\n", False),
    ("6\n1 10\n2 3\n4 5\n6 7\n8 9\n11 12\n", False),
]


