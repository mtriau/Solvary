KV_EDITORIAL = (
    "Keep one dict `key -> (value, expire_at | None)`; a key is alive at `ts` when"
    " `expire_at is None or ts < expire_at`. Every read-side command filters through that"
    " predicate, so level 3 is a one-line change to each query. For backups store"
    " *remaining* TTL (`expire_at - ts`) and re-add `ts` on restore. The pacing trap is"
    " level 2's sorting/formatting — do it with `sorted()` and a join, don't hand-roll it."
)


