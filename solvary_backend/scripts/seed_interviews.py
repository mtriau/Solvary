def _cases(inputs: list[tuple[str, bool]], solve: Callable[[str], list[str]]) -> list[dict]:
    out = []
    for stdin, is_sample in inputs:
        lines = solve(stdin)
        assert lines, "every case must produce output"
        out.append(
            {"stdin": stdin, "expected_stdout": "\n".join(lines) + "\n", "is_sample": is_sample}
        )
    return out


def _build_problem(
    slug: str,
    title: str,
    difficulty: str,
    statement_md: str,
    tags: list[str],
    starter: dict[str, str],
    cases: list[dict],
    is_public: bool,
    editorial_md: str | None,
) -> tuple[Problem, list[TestCase]]:
    pid = f"prob_{uuid.uuid4().hex[:8]}"
    problem = Problem(
        id=pid,
        slug=slug,
        title=title,
        difficulty=difficulty,  # type: ignore[arg-type]
        statement_md=statement_md,
        tags=tags,
        starter_code=starter,
        editorial_md=editorial_md,
        is_public=is_public,
    )
    testcases = [
        TestCase(
            id=f"tc_{uuid.uuid4().hex[:8]}",
            problem_id=pid,
            ordinal=i + 1,
            stdin=c["stdin"],
            expected_stdout=c["expected_stdout"],
            is_sample=c["is_sample"],
        )
        for i, c in enumerate(cases)
    ]
    return problem, testcases


def kv_level_problems() -> list[tuple[Problem, list[TestCase]]]:
    out = []
    for level, ((title, statement), inputs) in enumerate(zip(LEVEL_STATEMENTS, LEVEL_CASES), 1):
        timed = level >= 3

        def solve(stdin: str, timed: bool = timed) -> list[str]:
            return KVStore().run(stdin, timed)

        out.append(
            _build_problem(
                slug=f"kv-store-level-{level}",
                title=f"Key-Value Store — {title}",
                difficulty=["easy", "easy", "medium", "hard"][level - 1],
                statement_md=statement,
                tags=["interview", "design", "hash-map"],
                starter={"python": KV_STARTER_PY, "javascript": KV_STARTER_JS},
                cases=_cases(inputs, solve),
                is_public=False,
                editorial_md=KV_EDITORIAL,
            )
        )
    return out


def merge_intervals_problem() -> tuple[Problem, list[TestCase]]:
    return _build_problem(
        slug="merge-intervals",
        title="Merge Intervals",
        difficulty="medium",
        statement_md=(
            "Given `n` closed intervals, merge all overlapping ones and print the result"
            " sorted by start.\n\n### Input\nFirst line: `n`. Then `n` lines `a b` with"
            " `a ≤ b`.\n\n### Output\nThe merged intervals, one per line as `a b`.\n\n"
            "### Example\n```\nInput:\n4\n1 3\n2 6\n8 10\n15 18\n\nOutput:\n1 6\n8 10\n15 18\n```\n"
        ),
        tags=["array", "sorting"],
        starter={
            "python": (
                "import sys\n\n"
                "data = sys.stdin.read().split()\n"
                "# n = int(data[0]); pairs = data[1:]\n"
            ),
            "javascript": (
                "const data = require('fs').readFileSync(0, 'utf8')\n"
                "  .split(/\\s+/).filter(Boolean).map(Number);\n"
                "// const [n, ...pairs] = data;\n"
            ),
        },
        cases=_cases(MERGE_INPUTS, merge_intervals),
        is_public=True,
        editorial_md=(
            "Sort by start, then sweep: extend the last merged interval while the next"
            " start ≤ its end."
        ),
    )


